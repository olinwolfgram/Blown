function aa222_apply_simulink_physics_update(modelName)
%AA222_APPLY_SIMULINK_PHYSICS_UPDATE Rebuild the active aero path in Simulink.
%   This patches the current model so the live plant uses:
%   - eCalc-derived RPM-to-thrust
%   - actuator-disk slipstream per prop
%   - four wing strip-type subsystems
%   - an elevator-driven tail subsystem

if nargin < 1 || isempty(modelName)
    modelName = 'blown_wing_model';
end

init_params;
assign_aliases_to_base(params, initial_pos_ned, initial_vel_body, initial_euler, initial_rates);

open_system(modelName);

update_propulsion_functions(modelName);
rebuild_aero_sectioned(modelName);
connect_top_level_controls(modelName);

save_system(modelName);
fprintf('Updated %s with sectioned blown-wing aero and tail control wiring.\n', modelName);
end

function assign_aliases_to_base(params, initial_pos_ned, initial_vel_body, initial_euler, initial_rates)
assignin('base', 'params', params);
assignin('base', 'initial_pos_ned', initial_pos_ned);
assignin('base', 'initial_vel_body', initial_vel_body);
assignin('base', 'initial_euler', initial_euler);
assignin('base', 'initial_rates', initial_rates);

fields = {
    'lt','D_prop','prop_rpm_grid','prop_thrust_grid','alpha_deg_grid', ...
    'cl_clean_baseline','cl_blow_only','cl_flap_only','cl_all_high_lift', ...
    'cd_clean_baseline','cd_blow_only','cd_flap_only','cd_all_high_lift', ...
    'cm_clean_baseline','cm_blow_only','cm_flap_only','cm_all_high_lift', ...
    'y_dist','b','c','cg_x_m','prop_axial_x_m','flap_span_fraction', ...
    'flap_deflection_slow','k_span_expansion','S_ht','c_ht','b_ht', ...
    'CL_alpha_ht','CL_delta_e'
    };
for i = 1:numel(fields)
    assignin('base', fields{i}, params.(fields{i}));
end
end

function update_propulsion_functions(modelName)
set_matlab_function_script(modelName, 'Propulsion_and_Slipstream/RPM_to_Thrust', rpm_to_thrust_script());
set_matlab_function_script(modelName, 'Propulsion_and_Slipstream/Slip_Stream', slipstream_script());

configure_chart_parameters(modelName, 'Propulsion_and_Slipstream/RPM_to_Thrust', ...
    {'prop_rpm_grid', 'prop_thrust_grid'});
configure_chart_parameters(modelName, 'Propulsion_and_Slipstream/Slip_Stream', ...
    {'D_prop'});
cleanup_chart_data(modelName, 'Propulsion_and_Slipstream/RPM_to_Thrust', ...
    {'RPMs', 'rho'}, {'Thrusts'}, {'prop_rpm_grid', 'prop_thrust_grid'});
cleanup_chart_data(modelName, 'Propulsion_and_Slipstream/Slip_Stream', ...
    {'Thrusts', 'Va', 'rho'}, {'V_slip'}, {'D_prop'});
end

function rebuild_aero_sectioned(modelName)
aeroPath = [modelName '/Aerodynamics_Strip_Theory'];

ensure_inport(aeroPath, 'Control_Cmds', 5, [35, 290, 65, 304]);
comment_legacy_aero_blocks(aeroPath);
disconnect_outport(aeroPath, 'Aero_Forces');
disconnect_outport(aeroPath, 'Aero_Moments');

ensure_block('simulink/Signal Routing/Demux', [aeroPath '/Control_Demux'], [110, 270, 145, 320]);
set_param([aeroPath '/Control_Demux'], 'Outputs', '2');

create_wing_section_subsystem(aeroPath, 'Wing_Clean_NoFlap', [250, 40, 470, 140], false, false);
create_wing_section_subsystem(aeroPath, 'Wing_Blown_NoFlap', [250, 165, 470, 265], true, false);
create_wing_section_subsystem(aeroPath, 'Wing_Clean_Flap', [250, 290, 470, 390], false, true);
create_wing_section_subsystem(aeroPath, 'Wing_Blown_Flap', [250, 415, 470, 515], true, true);
create_tail_subsystem(aeroPath, 'Tail_Aero', [250, 540, 470, 640]);

ensure_block('simulink/Math Operations/Sum', [aeroPath '/Wing_Force_Sum'], [575, 190, 595, 260]);
ensure_block('simulink/Math Operations/Sum', [aeroPath '/Wing_Moment_Sum'], [575, 355, 595, 425]);
ensure_block('simulink/Math Operations/Sum', [aeroPath '/Total_Force_Sum'], [760, 250, 780, 300]);
ensure_block('simulink/Math Operations/Sum', [aeroPath '/Total_Moment_Sum'], [760, 390, 780, 440]);
set_param([aeroPath '/Wing_Force_Sum'], 'Inputs', '++++');
set_param([aeroPath '/Wing_Moment_Sum'], 'Inputs', '++++');
set_param([aeroPath '/Total_Force_Sum'], 'Inputs', '++');
set_param([aeroPath '/Total_Moment_Sum'], 'Inputs', '++');

safe_add_line(aeroPath, 'Control_Cmds/1', 'Control_Demux/1');

wingNames = {'Wing_Clean_NoFlap', 'Wing_Blown_NoFlap', 'Wing_Clean_Flap', 'Wing_Blown_Flap'};
for i = 1:numel(wingNames)
    safe_add_line(aeroPath, 'V_b/1', [wingNames{i} '/1']);
    safe_add_line(aeroPath, 'rho1/1', [wingNames{i} '/2']);
    safe_add_line(aeroPath, 'V_slip/1', [wingNames{i} '/3']);
    safe_add_line(aeroPath, 'Control_Demux/2', [wingNames{i} '/4']);
    safe_add_line(aeroPath, [wingNames{i} '/1'], sprintf('Wing_Force_Sum/%d', i));
    safe_add_line(aeroPath, [wingNames{i} '/2'], sprintf('Wing_Moment_Sum/%d', i));
end

safe_add_line(aeroPath, 'V_b/1', 'Tail_Aero/1');
safe_add_line(aeroPath, 'Omega/1', 'Tail_Aero/2');
safe_add_line(aeroPath, 'rho1/1', 'Tail_Aero/3');
safe_add_line(aeroPath, 'Control_Demux/1', 'Tail_Aero/4');

safe_add_line(aeroPath, 'Wing_Force_Sum/1', 'Total_Force_Sum/1');
safe_add_line(aeroPath, 'Tail_Aero/1', 'Total_Force_Sum/2');
safe_add_line(aeroPath, 'Wing_Moment_Sum/1', 'Total_Moment_Sum/1');
safe_add_line(aeroPath, 'Tail_Aero/2', 'Total_Moment_Sum/2');
safe_add_line(aeroPath, 'Total_Force_Sum/1', 'Aero_Forces/1');
safe_add_line(aeroPath, 'Total_Moment_Sum/1', 'Aero_Moments/1');
end

function connect_top_level_controls(modelName)
safe_add_line(modelName, 'Demux/2', 'Aerodynamics_Strip_Theory/5');
end

