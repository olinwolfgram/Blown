function recreate_subsystem(subPath, position)
if exist_block(subPath)
    delete_block(subPath);
end
add_block('simulink/Ports & Subsystems/Subsystem', subPath, 'Position', position);
innerBlocks = find_system(subPath, 'SearchDepth', 1, 'Type', 'Block');
for i = 2:numel(innerBlocks)
    delete_block(innerBlocks{i});
end
end

function tf = exist_block(path)
try
    get_param(path, 'Handle');
    tf = true;
catch
    tf = false;
end
end

function ensure_block(libPath, dstPath, position)
if ~exist_block(dstPath)
    add_block(libPath, dstPath, 'Position', position);
else
    set_param(dstPath, 'Position', position);
end
end

function ensure_inport(subsystemPath, name, portNumber, position)
path = [subsystemPath '/' name];
if ~exist_block(path)
    add_block('simulink/Sources/In1', path, 'Position', position, 'Port', num2str(portNumber));
else
    set_param(path, 'Port', num2str(portNumber), 'Position', position);
end
end

function comment_legacy_aero_blocks(aeroPath)
legacyBlocks = {
    '1X3_Zero','Atan2','CD','CL','CM','C_Y','C_l_Roll','C_n_Yaw','Coefficients', ...
    'Constant','Constant1','Constant2','Constant3','Constant4','Demux','Divide', ...
    'Dot Product','Gain','Gain1','Gain2','Lever_Arm_Constant','MATLAB Function1', ...
    'Pitch_gain','Product','Product1','Product2','Roll_Pitch_Yaw_moments', ...
    'Selector','Sqrt','Square','Square1','Sum','Sum of Elements','Sum2','Sum3', ...
    'Sum4','Sum5','Unblown_Aero','Horizontal_Tail_Model'
    };
for i = 1:numel(legacyBlocks)
    path = [aeroPath '/' legacyBlocks{i}];
    if exist_block(path)
        set_param(path, 'Commented', 'on');
    end
end
end

function disconnect_outport(aeroPath, outName)
ph = get_param([aeroPath '/' outName], 'PortHandles');
if isfield(ph, 'Inport') && ~isempty(ph.Inport)
    lineHandle = get_param(ph.Inport(1), 'Line');
    if isnumeric(lineHandle) && lineHandle ~= -1
        delete_line(lineHandle);
    end
end
end

function safe_add_line(systemPath, src, dst)
try
    add_line(systemPath, src, dst, 'autorouting', 'on');
catch ME
    if ~contains(ME.message, 'already exists') && ...
       ~contains(ME.message, 'The port is already connected') && ...
       ~contains(ME.message, 'destination port already has a line connection')
        rethrow(ME);
    end
end
end

