function set_matlab_function_script(modelName, blockPathSuffix, scriptText)
chartPath = [modelName '/' blockPathSuffix];
set_matlab_function_script_in_subsystem(fileparts(chartPath), erase(chartPath, [fileparts(chartPath) '/']), scriptText);
end

function set_matlab_function_script_in_subsystem(subPath, blockName, scriptText)
rt = sfroot;
chartPath = [subPath '/' blockName];
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', chartPath);
if isempty(chart)
    error('Could not find MATLAB Function block: %s', chartPath);
end
chart.Script = scriptText;
end

function configure_chart_parameters(modelName, blockPathSuffix, parameterNames)
chartPath = [modelName '/' blockPathSuffix];
configure_chart_parameters_in_subsystem(fileparts(chartPath), erase(chartPath, [fileparts(chartPath) '/']), parameterNames);
end

function configure_chart_parameters_in_subsystem(subPath, blockName, parameterNames)
rt = sfroot;
chartPath = [subPath '/' blockName];
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', chartPath);
if isempty(chart)
    error('Could not find MATLAB Function block: %s', chartPath);
end

allData = chart.find('-isa', 'Stateflow.Data');
for i = 1:numel(allData)
    if strcmp(allData(i).Scope, 'Parameter')
        delete(allData(i));
    end
end

for i = 1:numel(parameterNames)
    d = Stateflow.Data(chart);
    d.Name = parameterNames{i};
    d.Scope = 'Parameter';
end
end

function cleanup_chart_data(modelName, blockPathSuffix, inputNames, outputNames, parameterNames)
chartPath = [modelName '/' blockPathSuffix];
cleanup_chart_data_in_subsystem(fileparts(chartPath), erase(chartPath, [fileparts(chartPath) '/']), ...
    inputNames, outputNames, parameterNames);
end

function cleanup_chart_data_in_subsystem(subPath, blockName, inputNames, outputNames, parameterNames)
rt = sfroot;
chartPath = [subPath '/' blockName];
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', chartPath);
if isempty(chart)
    error('Could not find MATLAB Function block: %s', chartPath);
end

keep = [inputNames(:); outputNames(:); parameterNames(:)];
allData = chart.find('-isa', 'Stateflow.Data');
for i = 1:numel(allData)
    if ~any(strcmp(allData(i).Name, keep))
        delete(allData(i));
    end
end
end

function txt = rpm_to_thrust_script()
txt = sprintf([ ...
'function Thrusts = RPM_to_Thrust(RPMs, rho)\n' ...
'rpmGrid = prop_rpm_grid(:);\n' ...
'thrustGrid = prop_thrust_grid(:);\n' ...
'Thrusts = zeros(size(RPMs));\n' ...
'for i = 1:numel(RPMs)\n' ...
'    rpm = min(max(RPMs(i), rpmGrid(1)), rpmGrid(end));\n' ...
'    Thrusts(i) = max(interp1(rpmGrid, thrustGrid, rpm, ''linear''), 0);\n' ...
'end\n' ...
'end\n']);
end

function txt = slipstream_script()
txt = sprintf([ ...
'function V_slip = slipstream_calc(Thrusts, Va, rho)\n' ...
'A_prop = pi * (D_prop / 2)^2;\n' ...
'rho_safe = max(rho, 0.1);\n' ...
'T_safe = max(Thrusts, 0);\n' ...
'V_slip = sqrt(max(Va, 0)^2 + (2 .* T_safe) ./ max(rho_safe * A_prop, 1.0e-9));\n' ...
'end\n']);
end

function txt = wing_section_script(wantBlown, wantFlap)
txt = sprintf([ ...
'function [F_total, M_total] = Section_Aero(V_b, rho, V_slip, delta_flap)\n' ...
'wantBlown = %d;\n' ...
'wantFlap = %d;\n' ...
'F_total = zeros(3,1);\n' ...
'M_total = zeros(3,1);\n' ...
'Vb = reshape(V_b, 3, 1);\n' ...
'Vsl = V_slip(:);\n' ...
'u = Vb(1);\n' ...
'w = Vb(3);\n' ...
'Va = sqrt(sum(Vb.^2)) + 1.0e-3;\n' ...
'alpha = atan2(w, u);\n' ...
'alphaDeg = alpha * 180.0 / pi;\n' ...
'qInf = 0.5 * rho * Va^2;\n' ...
'posMask = y_dist(:) > 0;\n' ...
'posCenters = y_dist(posMask);\n' ...
'posSlip = Vsl(posMask);\n' ...
'blownHalfWidth = 0.5 * k_span_expansion * D_prop;\n' ...
'semiSpan = 0.5 * b;\n' ...
'flapEnd = flap_span_fraction * semiSpan;\n' ...
'edgeList = [0; flapEnd; semiSpan; max(posCenters - blownHalfWidth, 0); min(posCenters + blownHalfWidth, semiSpan)];\n' ...
'edgeList = sort(unique(edgeList));\n' ...
'flapMix = min(max(abs(delta_flap) / max(flap_deflection_slow, 1.0e-6), 0), 1);\n' ...
'ca = cos(alpha);\n' ...
'sa = sin(alpha);\n' ...
'Rsb = [ca, 0, -sa; 0, 1, 0; sa, 0, ca];\n' ...
'for i = 1:(numel(edgeList) - 1)\n' ...
'    y0 = edgeList(i);\n' ...
'    y1 = edgeList(i + 1);\n' ...
'    width = y1 - y0;\n' ...
'    if width <= 1.0e-6\n' ...
'        continue;\n' ...
'    end\n' ...
'    yMid = 0.5 * (y0 + y1);\n' ...
'    isFlapRegion = (yMid <= flapEnd + 1.0e-9);\n' ...
'    overlapMask = (posCenters + blownHalfWidth > y0) & (posCenters - blownHalfWidth < y1);\n' ...
'    isBlownRegion = any(overlapMask);\n' ...
'    if isFlapRegion ~= wantFlap || isBlownRegion ~= wantBlown\n' ...
'        continue;\n' ...
'    end\n' ...
'    qLocal = qInf;\n' ...
'    if isBlownRegion\n' ...
'        vLocal = mean(posSlip(overlapMask));\n' ...
'        qLocal = 0.5 * rho * vLocal^2;\n' ...
'    end\n' ...
'    if wantBlown\n' ...
'        clNoFlap = interp1(alpha_deg_grid, cl_blow_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cdNoFlap = interp1(alpha_deg_grid, cd_blow_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cmNoFlap = interp1(alpha_deg_grid, cm_blow_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'        clFlap = interp1(alpha_deg_grid, cl_all_high_lift, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cdFlap = interp1(alpha_deg_grid, cd_all_high_lift, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cmFlap = interp1(alpha_deg_grid, cm_all_high_lift, alphaDeg, ''linear'', ''extrap'');\n' ...
'    else\n' ...
'        clNoFlap = interp1(alpha_deg_grid, cl_clean_baseline, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cdNoFlap = interp1(alpha_deg_grid, cd_clean_baseline, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cmNoFlap = interp1(alpha_deg_grid, cm_clean_baseline, alphaDeg, ''linear'', ''extrap'');\n' ...
'        clFlap = interp1(alpha_deg_grid, cl_flap_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cdFlap = interp1(alpha_deg_grid, cd_flap_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'        cmFlap = interp1(alpha_deg_grid, cm_flap_only, alphaDeg, ''linear'', ''extrap'');\n' ...
'    end\n' ...
'    if wantFlap\n' ...
'        CL = clNoFlap + flapMix * (clFlap - clNoFlap);\n' ...
'        CD = cdNoFlap + flapMix * (cdFlap - cdNoFlap);\n' ...
'        Cm = cmNoFlap + flapMix * (cmFlap - cmNoFlap);\n' ...
'    else\n' ...
'        CL = clNoFlap;\n' ...
'        CD = cdNoFlap;\n' ...
'        Cm = cmNoFlap;\n' ...
'    end\n' ...
'    areaStrip = c * width;\n' ...
'    Fstab = qLocal * areaStrip * [-CD; 0; -CL];\n' ...
'    Fbody = Rsb * Fstab;\n' ...
'    Maero = qLocal * areaStrip * [0; Cm * c; 0];\n' ...
'    y = yMid;\n' ...
'    rVec = [prop_axial_x_m - cg_x_m; y; 0];\n' ...
'    Mlever = cross(rVec, Fbody);\n' ...
'    F_total = F_total + Fbody;\n' ...
'    M_total = M_total + Maero + Mlever;\n' ...
'    y = -yMid;\n' ...
'    rVec = [prop_axial_x_m - cg_x_m; y; 0];\n' ...
'    Mlever = cross(rVec, Fbody);\n' ...
'    F_total = F_total + Fbody;\n' ...
'    M_total = M_total + Maero + Mlever;\n' ...
'end\n' ...
'end\n'], wantBlown, wantFlap);
end

function txt = tail_aero_script()
txt = sprintf([ ...
'function [F_total, M_total] = Tail_Aero(V_b, Omega, rho, delta_e)\n' ...
'F_total = zeros(3,1);\n' ...
'M_total = zeros(3,1);\n' ...
'Vb = reshape(V_b, 3, 1);\n' ...
'Wb = reshape(Omega, 3, 1);\n' ...
'rTail = [-lt; 0; 0];\n' ...
'Vtail = Vb + cross(Wb, rTail);\n' ...
'u_t = Vtail(1);\n' ...
'w_t = Vtail(3);\n' ...
'Va_t = sqrt(sum(Vtail.^2)) + 0.1;\n' ...
'alpha_t = atan2(w_t, u_t);\n' ...
'qTail = 0.5 * rho * Va_t^2;\n' ...
'CL = CL_alpha_ht * alpha_t + CL_delta_e * delta_e;\n' ...
'CD = 0.02 + 0.06 * CL^2;\n' ...
'Cm = -0.15 * delta_e;\n' ...
'ca = cos(alpha_t);\n' ...
'sa = sin(alpha_t);\n' ...
'Rsb = [ca, 0, -sa; 0, 1, 0; sa, 0, ca];\n' ...
'Fstab = qTail * S_ht * [-CD; 0; -CL];\n' ...
'Fbody = Rsb * Fstab;\n' ...
'Mbody = qTail * S_ht * [0; Cm * c_ht; 0] + cross(rTail, Fbody);\n' ...
'F_total = Fbody;\n' ...
'M_total = Mbody;\n' ...
'end\n']);
end
